import unreal

def run():
    assets = [
        "/Game/MetaHumans/Common/Face/ABP_Face",
        "/Game/MetaHumans/Common/Face/ABP_Face_PostProcess"
    ]
    
    for path in assets:
        print(f"\n================ AnimBP: {path} ================")
        abp = unreal.load_object(None, path)
        if not abp:
            print("  ERROR: Could not load blueprint")
            continue
            
        print(f"  Class: {abp.get_class().get_name()}")
        
        # Check parent class
        try:
            print(f"  Parent Class: {abp.parent_class.get_name()}")
        except Exception as e:
            print(f"  Failed to get parent class: {e}")
            
        try:
            print(f"  Parent Class via property: {abp.get_editor_property('parent_class').get_name()}")
        except Exception as e:
            print(f"  Failed to get parent class via property: {e}")
            
        # Try to print skeleton
        try:
            print(f"  Target Skeleton: {abp.target_skeleton.get_name()}")
        except Exception as e:
            print(f"  Failed target skeleton: {e}")

        # Let's inspect variables of the AnimInstance class generated by this blueprint
        try:
            generated_class = abp.generated_class()
            print(f"  Generated Class: {generated_class.get_name()}")
            
            # Print all properties of the generated class
            print("  Variables:")
            for prop in generated_class.get_property_names():
                prop_val = None
                try:
                    # check if we can get a default or type info
                    pass
                except:
                    pass
                print(f"    {prop}")
        except Exception as e:
            print(f"  Failed generated class inspection: {e}")

if __name__ == "__main__":
    run()
